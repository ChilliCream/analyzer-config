    [Fact]
    public async Task Analyze_Should_ReplaceWithContainingType_When_DeclaringTypeIsNested()
    {
        // arrange
        const string source =
            """
            class Outer
            {
                public class Base
                {
                    public class Nested;
                }
            }

            class Derived : Outer.Base;

            class C
            {
                {|#0:Derived|}.Nested item = null!;
            }
            """;

        var test = CreateTest(source);
        test.ExpectedDiagnostics.Add(
            new DiagnosticResult("CCA0003", DiagnosticSeverity.Info)
                .WithLocation(0)
                .WithArguments("Nested", "Outer.Base"));

        // act & assert
        await test.RunAsync(TestContext.Current.CancellationToken);
    }

