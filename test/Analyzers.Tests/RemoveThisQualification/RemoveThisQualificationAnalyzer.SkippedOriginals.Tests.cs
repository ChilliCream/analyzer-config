namespace ChilliCream.Analyzers.Tests;

public sealed partial class RemoveThisQualificationAnalyzerTests
{
    [Fact]
    public async Task Analyze_Should_ReportNothing_When_AccessHasError()
    {
        // arrange
        var source = WithWidget(
            """
            [Obsolete("Old", true)] private int _old;

            int M() => {|CS0619:this._old|};
            """);

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportNothing_When_CommentAfterDot()
    {
        // arrange
        var source = WithWidget("int M() => this./* keep */_count;");

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportNothing_When_CommentAfterThis()
    {
        // arrange
        var source = WithWidget("int M() => this/* keep */._count;");

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportNothing_When_DirectiveInsideAccess()
    {
        // arrange
        var source = WithWidget(
            """
            int M() => this
            #if DEBUG
                ._count;
            #else
                ._other;
            #endif
            """);

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportNothing_When_GeneratedCode()
    {
        // arrange
        var source = "// <auto-generated/>\n" + WithWidget("int M() => this._count;");

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportThis_When_DirectiveEndsBeforeThis()
    {
        // arrange
        var source = WithWidget(
            """
            public int Y;

            void M()
            {
            #if true
                _count = 1;
            #else
                _count = 2;
            #endif
                [|this.|]Y = 3;
            }
            """);

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportThis_When_DirectiveEndsRightBeforeThis()
    {
        // arrange
        var source = WithWidget(
            """
            public int Y;

            void M()
            {
            #if true
                _count = 1;
            #else
                _count = 2;
            #endif
            [|this.|]Y = 3;
            }
            """);

        // act & assert
        await VerifyAsync(source);
    }

    [Fact]
    public async Task Analyze_Should_ReportThis_When_LineBreakBeforeDot()
    {
        // arrange
        var source = WithWidget(
            """
            int M() => [|this
                .|]_count;
            """);

        // act & assert
        await VerifyAsync(source);
    }
}
